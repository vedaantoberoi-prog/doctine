/** Copies the emergency patterns from netlify/lib/safety.mjs into public/index.html, so the page (used inside Claude) and the server apply the same rules.
 *  Run after editing safety.mjs:  node tools/sync-safety-rules.mjs   (tests/functions.test.mjs fails if they differ) */
import { readFileSync, writeFileSync } from "node:fs";
import { RULE_LIST } from "../netlify/lib/safety.mjs";
const file = new URL("../public/index.html", import.meta.url);
const html = readFileSync(file, "utf8");
const start = "/* SAFETY-RULES:START", end = "/* SAFETY-RULES:END */";
const a = html.indexOf(start), b = html.indexOf(end);
if (a < 0 || b < 0) throw new Error("markers not found in index.html");
const em = RULE_LIST.filter((r) => r.id !== "self_harm").map((r) => r.re.toString());
const sh = RULE_LIST.find((r) => r.id === "self_harm").re.toString();
const block = `${start} (generated by tools/sync-safety-rules.mjs from netlify/lib/safety.mjs — do not edit by hand) */\nconst EMERG=[${em.join(",\n ")}];\nconst SELFHARM=${sh};\n`;
writeFileSync(file, html.slice(0, a) + block + html.slice(b));
console.log(`copied ${em.length + 1} patterns into public/index.html`);
